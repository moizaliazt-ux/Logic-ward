/**
 * Internal notification email sent to the Logicward contact mailbox.
 */
function escapeHtml(value) {
	return String(value || '').replace(/[&<>"']/g, (character) => ({
		'&': '&amp;',
		'<': '&lt;',
		'>': '&gt;',
		'"': '&quot;',
		"'": '&#39;',
	})[character]);
}

